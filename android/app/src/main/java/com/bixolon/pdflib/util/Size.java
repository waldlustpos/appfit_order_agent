package com.bixolon.pdflib.util;

/** BIXOLON Bixolon_pdf.aar 스텁 — 사유는 com.bixolon.pdflib.License javadoc 참고. */
public class Size {
    private final int width;
    private final int height;

    public Size(int width, int height) {
        this.width = width;
        this.height = height;
    }

    public int getWidth() {
        return width;
    }

    public int getHeight() {
        return height;
    }
}
